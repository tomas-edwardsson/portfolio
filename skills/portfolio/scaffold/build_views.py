DONE_STATES = {"done", "dropped", "promoted"}
GENERATED = "<!-- GENERATED by build-views.sh — do not edit by hand -->"


def portfolio_name(root):
    """Optional display name for the HTML view, from a .title file."""
    p = root / ".title"
    if p.is_file():
        return p.read_text(encoding="utf-8").strip()
    return ""


def parse_frontmatter(text):
    """Return (frontmatter dict, body str). Tolerates missing frontmatter."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    fm = {}
    i = 1
    while i < len(lines) and lines[i].strip() != "---":
        line = lines[i]
        i += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z][A-Za-z-]*):\s*(.*)$", line)
        if m:
            value = m.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            fm[m.group(1)] = value
    return fm, "\n".join(lines[i + 1:])


def parse_id_list(value):
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        value = value[1:-1]
    return [v.strip() for v in value.split(",") if v.strip()]


def first_body_line(body):
    """Return the first paragraph of the body as a single space-joined line.

    Skips leading headings/comments, then collects lines starting at the
    first text line and joins them (space-separated) until a blank line or
    a heading ends the paragraph.
    """
    lines = body.splitlines()
    start = None
    for idx, line in enumerate(lines):
        s = line.strip()
        if s and not s.startswith("#") and not s.startswith("<!--"):
            start = idx
            break
    if start is None:
        return ""
    parts = [lines[start].strip()]
    for line in lines[start + 1:]:
        s = line.strip()
        if not s or s.startswith("#"):
            break
        parts.append(s)
    return " ".join(parts)


def load_items(root):
    items, warnings = {}, []

    def add(path):
        fm, body = parse_frontmatter(path.read_text(encoding="utf-8"))
        if not fm:
            # No frontmatter at all — a plain reference doc (e.g. a story's
            # `brief`), not a portfolio item. Skip silently.
            return
        iid = fm.get("id")
        if not iid:
            warnings.append(f"{path}: missing id")
            return
        if iid in items:
            warnings.append(f"{path}: duplicate id {iid} (also in {items[iid]['file']})")
            return
        items[iid] = {
            "id": iid,
            "type": fm.get("type", ""),
            "title": fm.get("title", ""),
            "status": fm.get("status", ""),
            "horizon": fm.get("horizon", ""),
            "blocked_by": parse_id_list(fm.get("blocked-by", "")),
            "brief": fm.get("brief", ""),
            "artifact": fm.get("artifact", ""),
            "epic": fm.get("epic", ""),
            "summary": first_body_line(body),
            "file": str(path),
            "updated": fm.get("updated", ""),
            "completed": fm.get("completed", ""),
            "created": fm.get("created", ""),
            "story": fm.get("story", ""),
        }

    for path in sorted((root / "epics").glob("*/*.md")):
        add(path)
    inbox = root / "inbox"
    if inbox.is_dir():
        for path in sorted(inbox.glob("*.md")):
            add(path)
    return items, warnings


def validate(items):
    warnings = []
    for it in sorted(items.values(), key=lambda x: x["id"]):
        for dep in it["blocked_by"]:
            if dep not in items:
                warnings.append(f"{it['id']}: unknown blocked-by id {dep}")
        valid = {"future", "active", "blocked", "done", "dropped", "parked",
                 "promoted"}
        if it["status"] and it["status"] not in valid:
            warnings.append(f"{it['id']}: unknown status '{it['status']}'")
        if it["type"] == "idea" and it["horizon"] not in ("", "later", "next"):
            warnings.append(
                f"{it['id']}: idea horizon '{it['horizon']}' not supported "
                "(use later or next; promote the idea instead)")
    state = {}  # id -> 1 visiting, 2 done

    def visit(iid, stack):
        state[iid] = 1
        for dep in items[iid]["blocked_by"]:
            if dep not in items:
                continue
            if state.get(dep) == 1:
                warnings.append("dependency cycle: " + " -> ".join(stack + [dep]))
            elif dep not in state:
                visit(dep, stack + [dep])
        state[iid] = 2

    for iid in sorted(items):
        if iid not in state:
            visit(iid, [iid])
    return warnings


def pending_blockers(item, items):
    return [d for d in item["blocked_by"]
            if d in items and items[d]["status"] not in DONE_STATES]


def item_epic(item, items):
    """Parent epic dict for a story/task, or None."""
    eid = item.get("epic")
    return items.get(eid) if eid else None


def is_parked(item, items):
    """True if the item is parked, or its parent epic is parked (cascade)."""
    if item["status"] == "parked":
        return True
    e = item_epic(item, items)
    return bool(e and e["status"] == "parked")


def ship_date(item):
    """The date an item shipped: `completed` if set, else `updated`."""
    return item.get("completed") or item.get("updated") or ""


def within_days(date_str, today_str, days):
    """True if date_str is a valid ISO date within `days` before today_str."""
    try:
        d = datetime.date.fromisoformat(date_str)
        t = datetime.date.fromisoformat(today_str)
    except ValueError:
        return False
    return 0 <= (t - d).days <= days


def epic_horizon(item):
    if item["horizon"]:
        return item["horizon"]
    return "now" if item["status"] == "active" else "later"


def marks(item):
    m = ""
    if item["brief"]:
        m += " 📄"
    if item["artifact"]:
        m += " 🔗"
    return m


def blocked_suffix(item, items):
    pend = pending_blockers(item, items)
    return " ⛔ after " + ", ".join(pend) if pend else ""


def ships_after_line(item, items):
    pend = pending_blockers(item, items)
    if not pend:
        return ""
    parts = [f"{d} ({items[d]['title']})" for d in pend]
    return "  - _ships after: " + ", ".join(parts) + "_"


def stories_of(epic_id, items):
    return sorted((x for x in items.values()
                   if x["type"] == "story" and x["epic"] == epic_id),
                  key=lambda x: x["id"])


def epics(items):
    return sorted((x for x in items.values() if x["type"] == "epic"),
                  key=lambda x: x["id"])


def board_lane(item, items):
    """Which kanban lane a story/task card belongs in, or None if off-board."""
    if is_parked(item, items) or item["status"] in ("dropped", "done"):
        return None
    if item["status"] == "blocked" or pending_blockers(item, items):
        return "blocked"
    if item["status"] == "active":
        return "active"
    if item["status"] == "future":
        return "ready"
    return None


BOARD_LANES = [("blocked", "⛔ Blocked"), ("ready", "🎬 Ready for Dev"),
               ("active", "🏃 Active")]
# The per-epic board pane shows these three status columns (no Shipped —
# done work lives in the Braglog).
EPIC_LANES = [("ready", "Ready for Dev"), ("active", "Active"),
              ("blocked", "Blocked")]


def render_board(items, today):
    out = [GENERATED, "# Portfolio Board", "", f"_Last generated: {today}_", ""]
    cards = sorted((x for x in items.values() if x["type"] in ("story", "task")),
                   key=lambda x: x["id"])
    for lane, heading in BOARD_LANES:
        out += [f"## {heading}", ""]
        rows = [c for c in cards if board_lane(c, items) == lane]
        for c in rows:
            epic = item_epic(c, items)
            tag = f" — {epic['id']} {epic['title']}" if epic else ""
            out.append(f"- [{c['id']}] {c['title']}{tag}"
                       f"{marks(c)}{blocked_suffix(c, items)}")
        if not rows:
            out.append("_(none)_")
        out.append("")
    out += ["## 🏆 Shipped (last 30 days)", ""]
    shipped = [e for e in epics(items) if e["status"] == "done"
               and within_days(ship_date(e), today, 30)]
    shipped.sort(key=lambda e: ship_date(e), reverse=True)
    for e in shipped:
        out.append(f"- [{e['id']}] {e['title']} — {ship_date(e)}{marks(e)}")
    if not shipped:
        out.append("_(none)_")
    out.append("")
    return "\n".join(out) + "\n"


def _roadmap_epic_md(e, items, with_summary=False):
    """An epic as a <details> accordion listing its non-done stories."""
    open_stories = [s for s in stories_of(e["id"], items)
                    if s["status"] not in DONE_STATES]
    count = f"{len(open_stories)} stor{'y' if len(open_stories) == 1 else 'ies'}"
    lines = ["<details>",
             f"<summary>[{e['id']}] {e['title']}{marks(e)} — {count}"
             f"{blocked_suffix(e, items)}</summary>", ""]
    if with_summary and e["summary"]:
        lines.append(e["summary"])
    for s in open_stories:
        lines.append(f"- [{s['id']}] {s['title']} — `{s['status']}`"
                     f"{marks(s)}{blocked_suffix(s, items)}")
        after = ships_after_line(s, items)
        if after:
            lines.append(after)
    lines += ["</details>", ""]
    return lines


def render_roadmap(items, today):
    out = [GENERATED, "# Roadmap", "", f"_Last generated: {today}_", ""]
    future = [e for e in epics(items) if e["status"] == "future"]
    parked = [e for e in epics(items) if e["status"] == "parked"]
    ideas = sorted((x for x in items.values()
                    if x["type"] == "idea" and x["status"] == "future"),
                   key=lambda x: x["id"])
    next_ideas = [i for i in ideas if i["horizon"] == "next"]
    later_ideas = [i for i in ideas if i["horizon"] != "next"]

    out += ["## ⏭️ Next", ""]
    next_epics = [e for e in future if epic_horizon(e) == "next"]
    for e in next_epics:
        out += _roadmap_epic_md(e, items, with_summary=True)
    for i in next_ideas:
        summary = f" — {i['summary']}" if i["summary"] else ""
        out.append(f"- [{i['id']}] {i['title']} 💡{summary}")
    if not next_epics and not next_ideas:
        out.append("_(none)_")
    out.append("")

    out += ["## 🌅 Later", ""]
    later_epics = [e for e in future if epic_horizon(e) != "next"]
    for e in later_epics:
        out += _roadmap_epic_md(e, items)
    for i in later_ideas:
        summary = f" — {i['summary']}" if i["summary"] else ""
        out.append(f"- [{i['id']}] {i['title']} 💡{summary}")
    if not later_epics and not later_ideas:
        out.append("_(none)_")
    out.append("")

    out += ["## ⏸️ Parked", ""]
    for e in parked:
        out += _roadmap_epic_md(e, items, with_summary=True)
    if not parked:
        out.append("_(none)_")
    out.append("")
    return "\n".join(out) + "\n"


def month_label(date_str):
    try:
        d = datetime.date.fromisoformat(date_str)
    except ValueError:
        return "Undated"
    return d.strftime("%B %Y")


def render_braglog(items, today):
    out = [GENERATED, "# Braglog", "", f"_Last generated: {today}_", "",
           "_What's shipped, newest first._", ""]
    done = [x for x in items.values()
            if x["status"] == "done" and x["type"] in ("epic", "story")]
    done.sort(key=lambda x: (ship_date(x), x["id"]), reverse=True)
    current = None
    for x in done:
        label = month_label(ship_date(x))
        if label != current:
            current = label
            out += ["", f"## {label}", ""]
        epic = item_epic(x, items)
        tag = f" — {epic['id']} {epic['title']}" if epic else ""
        kind = "🏆" if x["type"] == "epic" else "•"
        out.append(f"- {ship_date(x)} {kind} [{x['id']}] {x['title']}{tag}")
    if not done:
        out.append("_(nothing shipped yet)_")
    out.append("")
    return "\n".join(out) + "\n"


