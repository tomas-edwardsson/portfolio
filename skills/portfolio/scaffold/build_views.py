def _h(text):
    return html_mod.escape(text, quote=True)


def _chip(iid):
    cls = {"E": "e", "S": "s", "T": "t", "I": "i"}.get(iid[:1], "t")
    return f'<span class="chip {cls}">{_h(iid)}</span>'


def _pill(status):
    return f'<span class="pill {_h(status)}">{_h(status)}</span>' if status else ""


def _marks_html(item):
    out = ""
    if item["brief"]:
        href = item["brief"]
        if href.startswith("portfolio/"):
            href = href[len("portfolio/"):]
        out += f' <a class="mark" href="{_h(href)}" title="brief">📄</a>'
    if item["artifact"]:
        out += f' <a class="mark" href="{_h(item["artifact"])}" title="artifact">🔗</a>'
    return out


def _blocked_html(item, items):
    pend = pending_blockers(item, items)
    if not pend:
        return ""
    return f'<span class="blk">⛔ after {_h(", ".join(pend))}</span>'


def _ships_html(item, items):
    pend = pending_blockers(item, items)
    if not pend:
        return ""
    parts = ", ".join(f"{d} ({items[d]['title']})" for d in pend)
    return f'<div class="ships">ships after: {_h(parts)}</div>'


def _story_row(s, items):
    return (f'<li>{_chip(s["id"])} <span class="t">{_h(s["title"])}</span> '
            f'{_pill(s["status"])}{_marks_html(s)} {_blocked_html(s, items)}'
            f'{_ships_html(s, items)}</li>')


def _flat_row(item, with_summary=True):
    summary = (f'<div class="sum">{_h(item["summary"])}</div>'
               if with_summary and item["summary"] else "")
    idea = " 💡" if item["type"] == "idea" else ""
    return (f'<li>{_chip(item["id"])} <span class="t">{_h(item["title"])}</span>'
            f'{idea}{_marks_html(item)}{summary}</li>')


def _epic_accent(epic_id):
    """A stable low-chroma tint var for an epic id, for spines and nodes."""
    try:
        n = int(epic_id[1:]) % 6
    except (ValueError, IndexError):
        n = 0
    return f"var(--e-{n})"


def _board_card(c, items, show_epic=True):
    """A story/task card: title is the hero; epic reduced to a tinted chip.

    No status pill — the column already encodes status. The left spine is the
    epic's tint (red when blocked); the full epic name lives in a tooltip.
    `show_epic=False` drops the epic chip (used inside a per-epic pane, where
    every card already belongs to the pane's epic).
    """
    epic = item_epic(c, items)
    ea = _epic_accent(epic["id"]) if epic else "var(--line)"
    ep = (f'<span class="ep-tag" title="{_h(epic["title"])}">{_h(epic["id"])}</span>'
          if epic and show_epic else "")
    blocked_cls = " blocked" if (c["status"] == "blocked"
                                 or pending_blockers(c, items)) else ""
    return (f'<li><div class="card{blocked_cls}" style="--ea:{ea}">'
            f'<span class="t">{_h(c["title"])}</span>'
            f'<span class="meta">{_chip(c["id"])}{ep}{_marks_html(c)}</span>'
            f'{_blocked_html(c, items)}</div></li>')


def _epic_pane(e, items, cards):
    """A single epic's board pane: header + Ready/Active/Blocked columns.

    Hidden by default; the rail nav reveals the selected pane. Cards omit the
    epic chip (the whole pane is the epic). Done work is a footer count only.
    """
    ea = _epic_accent(e["id"])
    mine = [c for c in cards if c["epic"] == e["id"]]
    lanes = []
    for lane, label in EPIC_LANES:
        rows = "".join(_board_card(c, items, show_epic=False)
                       for c in mine if board_lane(c, items) == lane)
        body = f'<ul>{rows}</ul>' if rows else '<p class="none">(none)</p>'
        lanes.append(f'<div class="lane"><h3>{label}</h3>{body}</div>')
    shipped_n = sum(1 for c in mine if c["status"] == "done")
    summ = (f'<p class="epic-sum">{_h(e["summary"])}</p>' if e["summary"] else "")
    foot = (f'<p class="pane-foot">{shipped_n} shipped → Braglog</p>'
            if shipped_n else "")
    return (f'<div class="epic-pane" data-epic="{_h(e["id"])}" hidden '
            f'style="--ea:{ea}"><div class="pane-head">{_chip(e["id"])}'
            f'<span class="pt">{_h(e["title"])}</span></div>{summ}'
            f'<div class="lanes lanes3">{"".join(lanes)}</div>{foot}</div>')


def _shipped_card(e, hot=False):
    """A shipped epic card. `hot` marks the single freshest ship (score-tick)."""
    ea = _epic_accent(e["id"])
    tick = '<span class="tick"></span>' if hot else ""
    return (f'<li><div class="card shipped" style="--ea:{ea}">'
            f'<span class="t">{_h(e["title"])}</span>{tick}'
            f'<span class="meta">{_chip(e["id"])}'
            f'<span class="d">{_h(ship_date(e))}</span></span></div></li>')


def _roadmap_acc(e, items, with_summary=False):
    open_stories = [s for s in stories_of(e["id"], items)
                    if s["status"] not in DONE_STATES]
    count = f"{len(open_stories)} stor{'y' if len(open_stories) == 1 else 'ies'}"
    rows = "".join(_story_row(s, items) for s in open_stories)
    body = f'<ul class="rows">{rows}</ul>' if rows else ""
    summary = (f'<p class="epic-sum">{_h(e["summary"])}</p>'
               if with_summary and e["summary"] else "")
    return (f'<details class="epic-acc"><summary>{_chip(e["id"])}'
            f'<span>{_h(e["title"])}</span>{_marks_html(e)}'
            f'<span class="count">{count}</span>{_blocked_html(e, items)}'
            f'</summary>{summary}{body}</details>')


def render_html(items, today, name=""):
    future = [e for e in epics(items) if e["status"] == "future"]
    parked = [e for e in epics(items) if e["status"] == "parked"]
    ideas = sorted((x for x in items.values()
                    if x["type"] == "idea" and x["status"] == "future"),
                   key=lambda x: x["id"])
    next_ideas = [i for i in ideas if i["horizon"] == "next"]
    later_ideas = [i for i in ideas if i["horizon"] != "next"]
    n_stories = sum(1 for x in items.values() if x["type"] == "story")
    n_tasks = sum(1 for x in items.values() if x["type"] == "task")
    n_active = sum(1 for x in items.values()
                   if x["type"] == "epic" and x["status"] == "active")
    n_shipped = sum(1 for x in items.values()
                    if x["type"] == "epic" and x["status"] == "done")

    cards = sorted((x for x in items.values() if x["type"] in ("story", "task")),
                   key=lambda x: x["id"])

    out = []
    eyebrow = f"{_h(name)} · work tracking · generated" if name \
        else "work tracking · generated"
    out.append(f'<header><div><div class="eyebrow">{eyebrow}</div>'
               '<h1>Portfolio</h1></div>'
               f'<div class="stamp">build-views.sh<br>{_h(today)}</div></header>')
    out.append('<div class="boxscore">'
                f'<div class="bs"><b class="o">{n_active}</b><span>Epics active</span></div>'
                f'<div class="bs"><b>{n_stories}</b><span>Stories</span></div>'
                f'<div class="bs"><b>{n_tasks}</b><span>Tasks</span></div>'
                f'<div class="bs"><b>{len(ideas)}</b><span>Ideas</span></div>'
                f'<div class="bs"><b class="o">{n_shipped}</b><span>Epics shipped</span></div>'
                '</div>')

    # Tab bar
    out.append('<nav class="tabs" role="tablist" aria-label="Portfolio views">'
               '<a href="#board" data-tab="board" id="tab-board" role="tab" '
               'aria-controls="board" aria-selected="true">Board</a>'
               '<a href="#roadmap" data-tab="roadmap" id="tab-roadmap" role="tab" '
               'aria-controls="roadmap" aria-selected="false">Roadmap</a>'
               '<a href="#braglog" data-tab="braglog" id="tab-braglog" role="tab" '
               'aria-controls="braglog" aria-selected="false">Braglog</a></nav>')

    # Board — a left epic rail + panes. The "All work" pane is the cross-epic
    # status board; each other pane is one epic's Ready/Active/Blocked columns.
    def _open_count(eid):
        return sum(1 for c in cards
                   if c["epic"] == eid and board_lane(c, items) is not None)

    # Only epics with open work appear in the rail — an epic whose stories are
    # all shipped/parked is "finished" and drops out of the board navigation
    # (it still lives in the Braglog / Roadmap).
    board_epics = sorted(
        (e for e in epics(items)
         if e["status"] in ("active", "future") and _open_count(e["id"]) > 0),
        key=lambda e: (0 if e["status"] == "active" else 1, e["id"]))

    all_lanes = []
    for lane, heading in BOARD_LANES:
        rows = "".join(_board_card(c, items) for c in cards
                       if board_lane(c, items) == lane)
        body = f'<ul>{rows}</ul>' if rows else '<p class="none">(none)</p>'
        all_lanes.append(f'<div class="lane"><h3>{heading}</h3>{body}</div>')
    shipped = [e for e in epics(items) if e["status"] == "done"
               and within_days(ship_date(e), today, 30)]
    shipped.sort(key=lambda e: ship_date(e), reverse=True)
    srows = "".join(_shipped_card(e, hot=(i == 0)) for i, e in enumerate(shipped))
    sbody = f'<ul>{srows}</ul>' if shipped else '<p class="none">(none)</p>'
    all_lanes.append(f'<div class="lane"><h3>🏆 Shipped · 30d</h3>{sbody}</div>')

    rail = ['<nav class="rail" aria-label="Epics">',
            '<a href="#board" data-epic-nav="all" class="active" '
            'style="--ea:var(--orange)"><span class="dot"></span>'
            '<span class="rl">All work</span></a>']
    for e in board_epics:
        rail.append(
            f'<a href="#board/{_h(e["id"])}" data-epic-nav="{_h(e["id"])}" '
            f'style="--ea:{_epic_accent(e["id"])}"><span class="dot"></span>'
            f'<span class="rl">{_chip(e["id"])}{_h(e["title"])}</span>'
            f'<span class="n">{_open_count(e["id"])}</span></a>')
    rail.append('</nav>')

    panes = [f'<div class="epic-pane" data-epic="all"><div class="lanes">'
             f'{"".join(all_lanes)}</div></div>']
    panes += [_epic_pane(e, items, cards) for e in board_epics]

    out.append(f'<section class="tab" id="board" role="tabpanel" '
               f'aria-labelledby="tab-board"><div class="board-wrap">'
               f'{"".join(rail)}<div class="panes">{"".join(panes)}</div>'
               f'</div></section>')

    # Roadmap
    r = ['<section class="tab" id="roadmap" role="tabpanel" '
         'aria-labelledby="tab-roadmap" hidden>']
    r.append('<h3 class="group">⏭️ Next</h3>')
    next_epics = [e for e in future if epic_horizon(e) == "next"]
    r += [_roadmap_acc(e, items, with_summary=True) for e in next_epics]
    if next_ideas:
        r.append('<ul class="flat">' + "".join(_flat_row(i) for i in next_ideas) + '</ul>')
    if not next_epics and not next_ideas:
        r.append('<p class="none">(none)</p>')
    r.append('<h3 class="group">🌅 Later</h3>')
    later_epics = [e for e in future if epic_horizon(e) != "next"]
    r += [_roadmap_acc(e, items) for e in later_epics]
    if later_ideas:
        r.append('<ul class="flat">' + "".join(_flat_row(i) for i in later_ideas) + '</ul>')
    if not later_epics and not later_ideas:
        r.append('<p class="none">(none)</p>')
    r.append('<h3 class="group">⏸️ Parked</h3>')
    r += [_roadmap_acc(e, items, with_summary=True) for e in parked] \
        or ['<p class="none">(none)</p>']
    r.append('</section>')
    out.append("".join(r))

    # Braglog — a chronological timeline; epic name shown only when it changes
    # down the list (kills repetition, keeps chronology). Epic completions are
    # elevated; the single freshest ship gets the orange score-tick.
    b = ['<section class="tab" id="braglog" role="tabpanel" '
         'aria-labelledby="tab-braglog" hidden><div class="brag">']
    done = [x for x in items.values()
            if x["status"] == "done" and x["type"] in ("epic", "story")]
    done.sort(key=lambda x: (ship_date(x), x["id"]), reverse=True)
    month_counts = {}
    for x in done:
        m = month_label(ship_date(x))
        month_counts[m] = month_counts.get(m, 0) + 1
    current = None
    last_eid = None
    open_ul = False
    for i, x in enumerate(done):
        label = month_label(ship_date(x))
        if label != current:
            if open_ul:
                b.append('</ul>')
            current = label
            last_eid = None
            b.append(f'<h3>{_h(label)}<span class="count">'
                     f'{month_counts[label]} shipped</span></h3><ul>')
            open_ul = True
        tick = '<span class="tick"></span>' if i == 0 else ""
        if x["type"] == "epic":
            ea = _epic_accent(x["id"])
            last_eid = None
            b.append(f'<li class="epic-done" style="--ea:{ea}">'
                     f'<span class="d">{_h(ship_date(x))}</span>'
                     f'<div class="c"><span class="t">🏆 {_h(x["title"])}</span>'
                     f'{tick}</div></li>')
        else:
            epic = item_epic(x, items)
            ea = _epic_accent(epic["id"]) if epic else "var(--line)"
            ep = ""
            if epic and epic["id"] != last_eid:
                ep = (f'<span class="ep-name" title="{_h(epic["title"])}">'
                      f'{_h(epic["id"])} {_h(epic["title"])}</span>')
            if epic:
                last_eid = epic["id"]
            b.append(f'<li style="--ea:{ea}">'
                     f'<span class="d">{_h(ship_date(x))}</span>'
                     f'<div class="c"><span class="t">{_h(x["title"])}</span>'
                     f'{tick}{ep}</div></li>')
    if open_ul:
        b.append('</ul>')
    if not done:
        b.append('<p class="none">(nothing shipped yet)</p>')
    b.append('</div></section>')
    out.append("".join(b))

    out.append('<footer>GENERATED by build-views.sh — do not edit. '
               'Source of truth: the item files in epics/ and inbox/.</footer>')

    script = (
        "<script>(function(){var t=['board','roadmap','braglog'];"
        "function all(q){return document.querySelectorAll(q);}"
        "function show(hash){var p=(hash||'board').split('/');var tab=p[0];"
        "if(t.indexOf(tab)<0)tab='board';"
        "t.forEach(function(x){document.getElementById(x).hidden=(x!==tab);"
        "var a=document.querySelector('[data-tab=\"'+x+'\"]');"
        "if(a){a.classList.toggle('active',x===tab);"
        "a.setAttribute('aria-selected',x===tab);}});"
        "if(tab==='board'){var ep=p[1]||'all';var ok=false;"
        "all('[data-epic]').forEach(function(n){var on=n.getAttribute('data-epic')===ep;"
        "n.hidden=!on;if(on)ok=true;});"
        "if(!ok){ep='all';all('[data-epic]').forEach(function(n){"
        "n.hidden=n.getAttribute('data-epic')!=='all';});}"
        "all('[data-epic-nav]').forEach(function(l){"
        "var on=l.getAttribute('data-epic-nav')===ep;l.classList.toggle('active',on);"
        "if(on)l.setAttribute('aria-current','true');else l.removeAttribute('aria-current');"
        "});}}"
        "function h(){show((location.hash||'#board').slice(1));}"
        "window.addEventListener('hashchange',h);h();})();</script>")

    return ('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            f'<title>{_h(name) + " " if name else ""}Portfolio</title>'
            f'<style>{HTML_CSS}</style></head>'
            f'<body><div class="wrap">{"".join(out)}</div>{script}</body></html>\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=Path(__file__).resolve().parent,
                        type=Path)
    args = parser.parse_args()
    root = args.root
    items, warnings = load_items(root)
    warnings += validate(items)
    today = datetime.date.today().isoformat()
    (root / "BOARD.md").write_text(render_board(items, today), encoding="utf-8")
    (root / "ROADMAP.md").write_text(render_roadmap(items, today), encoding="utf-8")
    (root / "BRAGLOG.md").write_text(render_braglog(items, today), encoding="utf-8")
    (root / "portfolio.html").write_text(
        render_html(items, today, portfolio_name(root)), encoding="utf-8")
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    print(f"Wrote {root / 'BOARD.md'}, {root / 'ROADMAP.md'}, "
          f"{root / 'BRAGLOG.md'} and {root / 'portfolio.html'}")


if __name__ == "__main__":
    main()
